'''
Создайте программу, которая определяет, сколько золотых монет нужно заплатить в таверне «Гарцующий Пони», с учётом того, кто вы такой. 
Разным гостям — разные скидки. Для уважаемых персон — особые условия!

Скидки:
Друг Гендальфа - 100%
Рейнджер - 50%
Хоббит - 20%
'''

print("Добро пожаловать в таверну 'Гарцующий Пони'!")

price = float(input("Так сколько вы нам за всё должны? "))

identity = input("А кто вы такие, позвольте узнать? ").lower().strip()

if identity == "друзья гендальфа":
    discount = 1.00
    print("Друзья Гендальфа? Вы ничего не должны! Всё за счёт заведения!")
elif identity == "рейнджер":
    discount = 0.50
    print("Рейнджер, говорите? Половину суммы оставьте себе, ещё пригодится.")
elif identity == "хоббит":
    discount = 0.20
    print("Хоббиты у нас всегда в почёте. Получаете скидку в пятую часть суммы.")
else:
    discount = 0.0
    print("Увы, для вас скидка не предусмотрена.")

final_price = price * (1 - discount)

print(f"Итоговая сумма к оплате: {final_price:.2f} золотых монет.")