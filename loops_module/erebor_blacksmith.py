'''
В древней кузне под горой Эребор юный гном-подмастерье проходит важное испытание. Наставник следит за каждым его движением. Цель — выковать обычный клинок, но строго по правилам.
Создай программу, в которой подмастерье проходит 10 этапов ковки клинка. На каждом этапе он наносит удар молотом, выбирая силу удара — целое число от 1 до 10.
'''

print("Горы Эребора. Сегодня ты, юный подмастерье, сдаёшь экзамен на кузнеца.")
print("Твоя задача — пройти 10 этапов ковки обычного клинка.")
print("Наставник смотрит внимательно. Будь точен: не слишком слабо, не слишком сильно.\n")

mistakes = 0

for stage in range(1, 11):
    print(f"\nЭтап {stage} — Удар молотом по заготовке.")
    power = int(input("Укажи силу удара (от 1 до 10): "))

    if 4 <= power <= 7:
        print("Наставник: Удар правильный! Продолжай, ученик!")
    elif power < 4:
        print("Наставник: Слишком слабо!")
        mistakes += 1
    elif power > 7:
        print("Наставник: Осторожнее! Такие удары могут вызвать трещины!")
        mistakes += 1
    else:
        print("Наставник: Что за странный удар? Я тебя такому не учил!")
        mistakes += 1

print("\nИспытание завершено.")

if mistakes >= 3:
    print("Наставник: Ты пока не готов. Продолжай учиться. Вернёшься через месяц.")
else:
    print("Наставник: Неплохо. Клинок не идеален, но ты прошёл испытание. Добро пожаловать в кузню.")