'''
Напишите программу, которая помогает классифицировать продукт по качеству и категории. Программа должна запросить у пользователя два значения:

- Уровень качества продукта (число от 1 до 10).
- Категорию продукта ("премиум", "эконом", "стандарт").

На основе введенных данных программа должна:

Определить качество продукта:
+ Если уровень от 1 до 3 (включительно), продукт считается плохого качества.
+ Если уровень от 4 до 6 (включительно), продукт считается среднего качества.
+ Если уровень от 7 до 10 (включительно), продукт считается высокого качества.

Вывести сообщение:
+ Если продукт высокого качества и категории "премиум", вывести: "Продукт премиум класса!".
+ Если продукт среднего качества и категории "стандарт", вывести: "Продукт стандартного качества".
+ Во всех других случаях вывести: "Обычный продукт".

Если пользователь ввел некорректные данные (уровень качества не от 1 до 10 или категория неверная), вывести сообщение об ошибке.
'''

# Запрашиваем ввод уровня качества продукта
quality_input = input("Введите уровень качества продукта (1-10): ")
quality = int(quality_input)

# Запрашиваем категорию продукта
category = input("Введите категорию продукта (премиум, эконом, стандарт): ").lower()

# Проверяем корректность ввода уровня качества
if quality >= 1 and quality <= 10:
    # Определяем качество продукта
    if 1 <= quality <= 3:
        print("Продукт плохого качества.")
    elif 4 <= quality <= 6:
        print("Продукт среднего качества.")
        if category == "стандарт":
            print("Продукт стандартного качества.")
        else:
            print("Обычный продукт.")
    elif 7 <= quality <= 10:
        print("Продукт высокого качества.")
        if category == "премиум":
            print("Продукт премиум класса!")
        else:
            print("Обычный продукт.")
else:
    print("Ошибка: уровень качества должен быть числом от 1 до 10.")